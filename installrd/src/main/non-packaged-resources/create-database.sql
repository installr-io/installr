/**
 * table: TRANSACTION_LOG
 */
CREATE TABLE IF NOT EXISTS PUBLIC.TRANSACTION_LOG (
	ID              UUID NOT NULL,
	NAMESPACE       CHARACTER VARYING(255) NOT NULL,
	BEGIN_TIMESTAMP TIMESTAMP NOT NULL,
	END_TIMESTAMP   TIMESTAMP,
	STATUS          ENUM('InProgress', 'Success', 'Failed', 'Canceled') NOT NULL,
	DAEMON_VERSION  CHARACTER VARYING(255) NOT NULL,
	CONSTRAINT TXLOG_PK PRIMARY KEY (ID)
);
CREATE UNIQUE INDEX TXLOG_PK_IDX ON PUBLIC.TRANSACTION_LOG (ID);

/**
 * table: PACKAGE_LOG
 */
CREATE TABLE IF NOT EXISTS PUBLIC.PACKAGE_LOG (
	ID                  BIGINT NOT NULL,
	NAMESPACE           CHARACTER VARYING(255) NOT NULL,
	PACKAGE_NAME        CHARACTER VARYING(255) NOT NULL,
	PACKAGE_INFO        JSON NOT NULL,
	REPOSITORY_ID       CHARACTER VARYING(255) NOT NULL,
	"ACTION"            ENUM('Delete', 'Install', 'ReInstall', 'Update') NOT NULL,
	ACTION_BY_TXID      UUID NOT NULL,
	ACTION_TIMESTAMP    TIMESTAMP NOT NULL,
	STATUS              ENUM('InProgress', 'Success', 'Failed', 'Canceled') NOT NULL,
	CONSTRAINT PKG_LOG_PK PRIMARY KEY (ID),
	CONSTRAINT PKG_LOG_TXID_FK FOREIGN KEY (ACTION_BY_TXID) REFERENCES PUBLIC.TRANSACTION_LOG(ID) ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX IF NOT EXISTS PKG_LOG_TXID_FK_IDX ON PUBLIC.PACKAGE_LOG (ACTION_BY_TXID);
CREATE UNIQUE INDEX IF NOT EXISTS PKG_LOG_PK_IDX ON PUBLIC.PACKAGE_LOG (ID);
CREATE SEQUENCE IF NOT EXISTS PUBLIC.PACKAGE_LOG_SEQ START WITH 1 INCREMENT BY 1;

/**
 * table: ITEM_LOG
 */
CREATE TABLE IF NOT EXISTS PUBLIC.ITEM_LOG (
	ID                BIGINT NOT NULL,
	NAMESPACE         CHARACTER VARYING(255) NOT NULL,
	PACKAGE_NAME      CHARACTER VARYING(255) NOT NULL,
	"PATH"            CHARACTER VARYING(255) NOT NULL,
	VERSION           CHARACTER VARYING(255) NOT NULL,
	MEDIA_TYPE        CHARACTER VARYING(255) NOT NULL,
	ENCODING          CHARACTER VARYING(255) NOT NULL,
	HASH              CHARACTER VARYING(255) NOT NULL,
	INSTALLED_BY_TXID UUID NOT NULL,
	INSTALLED_ON      TIMESTAMP NOT NULL,
	ERROR             BOOLEAN NOT NULL,
	CONSTRAINT ITEM_LOG_PK PRIMARY KEY (ID),
	CONSTRAINT ITEM_LOG_NS_PKG_PATH_UC UNIQUE (PACKAGE_NAME,NAMESPACE,"PATH"),
	CONSTRAINT ITEM_LOG_TXID_FK FOREIGN KEY (INSTALLED_BY_TXID) REFERENCES PUBLIC.TRANSACTION_LOG(ID) ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX IF NOT EXISTS ITEM_LOG_TXID_FK_IDX ON PUBLIC.ITEM_LOG (INSTALLED_BY_TXID);
CREATE UNIQUE INDEX IF NOT EXISTS ITEM_LOG_NS_PKG_PATH_UC_IDX ON PUBLIC.ITEM_LOG (NAMESPACE,PACKAGE_NAME,"PATH");
CREATE UNIQUE INDEX IF NOT EXISTS ITEM_LOG_PK_IDX ON PUBLIC.ITEM_LOG (ID);
CREATE SEQUENCE IF NOT EXISTS PUBLIC.ITEM_LOG_SEQ START WITH 1 INCREMENT BY 1;

/**
 * table: EVENT_LOG
 */
CREATE TABLE IF NOT EXISTS PUBLIC.EVENT_LOG (
	ID             BIGINT NOT NULL,
	NAMESPACE      CHARACTER VARYING(255) NOT NULL,
	TRANSACTION_ID UUID NOT NULL,
	EVENT          JSON NOT NULL,
	CONSTRAINT EVENT_LOG_PK PRIMARY KEY (ID),
	CONSTRAINT EVENT_LOG_TX_ID_FK FOREIGN KEY (TRANSACTION_ID) REFERENCES PUBLIC.TRANSACTION_LOG(ID) ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX IF NOT EXISTS EVENT_LOG_TX_ID_FK_IDX ON PUBLIC.EVENT_LOG (TRANSACTION_ID);
CREATE UNIQUE INDEX IF NOT EXISTS EVENT_LOG_PK_IDX ON PUBLIC.EVENT_LOG (ID);
CREATE SEQUENCE IF NOT EXISTS PUBLIC.EVENT_LOG_SEQ START WITH 1 INCREMENT BY 1;
