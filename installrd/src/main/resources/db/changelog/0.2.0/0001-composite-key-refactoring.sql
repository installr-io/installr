-- rename tables
ALTER TABLE PUBLIC.TRANSACTION_LOG RENAME TO PUBLIC.TRANSACTION_LOG_OLD;
ALTER TABLE PUBLIC.EVENT_LOG RENAME TO PUBLIC.EVENT_LOG_OLD;
ALTER TABLE PUBLIC.PACKAGE_LOG RENAME TO PUBLIC.PACKAGE_LOG_OLD;
ALTER TABLE PUBLIC.ITEM_LOG RENAME TO PUBLIC.ITEM_LOG_OLD;

-- re-create table: TRANSACTION_LOG
CREATE TABLE IF NOT EXISTS PUBLIC.TRANSACTION_LOG (
    NAMESPACE       CHARACTER VARYING(255) NOT NULL,
    TX_ID           UUID NOT NULL,
    BEGIN_TIMESTAMP TIMESTAMP NOT NULL,
    END_TIMESTAMP   TIMESTAMP,
    STATUS          ENUM('InProgress', 'Success', 'Failed', 'Canceled') NOT NULL,
    DAEMON_VERSION  CHARACTER VARYING(255) NOT NULL
);

-- re-create table: EVENT_LOG
CREATE TABLE IF NOT EXISTS PUBLIC.EVENT_LOG (
    NAMESPACE CHARACTER VARYING(255) NOT NULL,
    TX_ID     UUID NOT NULL,
    ID        UUID NOT NULL,
    EVENT     JSON NOT NULL
);

-- re-create table: PACKAGE_LOG
CREATE TABLE IF NOT EXISTS PUBLIC.PACKAGE_LOG (
    NAMESPACE        CHARACTER VARYING(255) NOT NULL,
    TX_ID            UUID NOT NULL,
    PACKAGE_NAME     CHARACTER VARYING(255) NOT NULL,
    PACKAGE_INFO     JSON NOT NULL,
    REPOSITORY_ID    CHARACTER VARYING(255) NOT NULL,
    "ACTION"         ENUM('Delete', 'Install', 'ReInstall', 'Update') NOT NULL,
    ACTION_TIMESTAMP TIMESTAMP NOT NULL,
    STATUS           ENUM('InProgress', 'Success', 'Failed', 'Canceled') NOT NULL
);

-- re-create table: ITEM_LOG
CREATE TABLE IF NOT EXISTS PUBLIC.ITEM_LOG (
    NAMESPACE    CHARACTER VARYING(255) NOT NULL,
    TX_ID        UUID NOT NULL,
    PACKAGE_NAME CHARACTER VARYING(255) NOT NULL,
    "PATH"       CHARACTER VARYING(255) NOT NULL,
    VERSION      CHARACTER VARYING(255) NOT NULL,
    MEDIA_TYPE   CHARACTER VARYING(255) NOT NULL,
    ENCODING     CHARACTER VARYING(255) NOT NULL,
    HASH         CHARACTER VARYING(255) NOT NULL,
    INSTALLED_ON TIMESTAMP NOT NULL,
    ERROR        BOOLEAN NOT NULL
);

-- migrate TRANSACTION_LOG data
INSERT INTO TRANSACTION_LOG
SELECT x.NAMESPACE, x.ID, x.BEGIN_TIMESTAMP, x.END_TIMESTAMP, x.STATUS, x.DAEMON_VERSION 
  FROM TRANSACTION_LOG_OLD x
 ORDER BY x.BEGIN_TIMESTAMP
;

-- migrate EVENT_LOG data
INSERT INTO EVENT_LOG
SELECT x.NAMESPACE, x.TRANSACTION_ID, RANDOM_UUID(), x.EVENT FORMAT JSON
  FROM EVENT_LOG_OLD x
 ORDER BY x.ID
;

-- migrate PACKAGE_LOG data
INSERT INTO PACKAGE_LOG 
SELECT x.NAMESPACE, x.ACTION_BY_TXID, x.PACKAGE_NAME, x.PACKAGE_INFO FORMAT JSON, x.REPOSITORY_ID, x."ACTION", x.ACTION_TIMESTAMP, x.STATUS
  FROM PACKAGE_LOG_OLD x
ORDER BY x.ACTION_TIMESTAMP
;

-- migrate ITEM_LOG data
INSERT INTO ITEM_LOG 
SELECT x.NAMESPACE, x.INSTALLED_BY_TXID, x.PACKAGE_NAME, x."PATH", x.VERSION, x.MEDIA_TYPE, x.ENCODING, x.HASH, x.INSTALLED_ON, x.ERROR
  FROM ITEM_LOG_OLD x
 ORDER BY x.INSTALLED_ON
;

-- drop old tables and sequences
DROP TABLE IF EXISTS PUBLIC.EVENT_LOG_OLD;
DROP TABLE IF EXISTS PUBLIC.ITEM_LOG_OLD;
DROP TABLE IF EXISTS PUBLIC.PACKAGE_LOG_OLD;
DROP TABLE IF EXISTS PUBLIC.TRANSACTION_LOG_OLD;
DROP SEQUENCE IF EXISTS PUBLIC.EVENT_LOG_SEQ;
DROP SEQUENCE IF EXISTS PUBLIC.ITEM_LOG_SEQ;
DROP SEQUENCE IF EXISTS PUBLIC.PACKAGE_LOG_SEQ;

-- re-create PKs and FKs
ALTER TABLE PUBLIC.TRANSACTION_LOG ADD CONSTRAINT TXLOG_PK PRIMARY KEY (NAMESPACE, TX_ID);

ALTER TABLE PUBLIC.PACKAGE_LOG ADD CONSTRAINT PKG_LOG_PK PRIMARY KEY (NAMESPACE, TX_ID, PACKAGE_NAME);
ALTER TABLE PUBLIC.PACKAGE_LOG ADD CONSTRAINT PKG_LOG_TX_FK FOREIGN KEY (NAMESPACE, TX_ID)
    REFERENCES PUBLIC.TRANSACTION_LOG(NAMESPACE, TX_ID) ON DELETE RESTRICT ON UPDATE RESTRICT;

ALTER TABLE PUBLIC.ITEM_LOG ADD CONSTRAINT ITEM_LOG_PK PRIMARY KEY (NAMESPACE, TX_ID, PACKAGE_NAME, "PATH");
ALTER TABLE PUBLIC.ITEM_LOG ADD CONSTRAINT ITEM_LOG_PKG_LOG_FK FOREIGN KEY (NAMESPACE, TX_ID, PACKAGE_NAME)
	REFERENCES PUBLIC.PACKAGE_LOG(NAMESPACE, TX_ID, PACKAGE_NAME) ON DELETE RESTRICT ON UPDATE RESTRICT;

ALTER TABLE PUBLIC.EVENT_LOG ADD CONSTRAINT EVENT_LOG_TX_FK FOREIGN KEY (NAMESPACE, TX_ID)
    REFERENCES PUBLIC.TRANSACTION_LOG(NAMESPACE, TX_ID) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE PUBLIC.EVENT_LOG ADD CONSTRAINT EVENT_LOG_PK PRIMARY KEY (NAMESPACE, TX_ID, ID);
