package io.installr.installrd.common.http.auth.provider;

import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.annotation.JsonSubTypes;
import com.fasterxml.jackson.annotation.JsonTypeInfo;

import lombok.Data;

@Data
@JsonTypeInfo(
    use = JsonTypeInfo.Id.NAME,
    include = JsonTypeInfo.As.EXISTING_PROPERTY,
    property = "type",
    visible = true,
    defaultImpl = ValueProviderConfig.class
)
@JsonSubTypes(
    {
        @JsonSubTypes.Type( value = HeaderValueProviderConfig.class, name = "header-value" )
    }
)
public class ValueProviderConfig {

    @JsonProperty( "type" )
    private ValueProviderType type = ValueProviderType.None;

}
